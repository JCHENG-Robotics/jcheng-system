#!/usr/bin/env bash
# Install the jcheng-system read-only /v1 gateway on the robot host.
#
# Run on the robot (10.42.0.218) as a user with sudo. It never starts or
# restarts the vendor container, never starts a motion gateway and never arms
# anything: the installed unit serves loopback-only GET traffic.
#
#   ./install-readonly-gateway.sh              # install + enable + start
#   ./install-readonly-gateway.sh --no-start   # install only
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_DIR=/etc/jcheng-system
ENV_FILE="${ENV_DIR}/readonly.env"
LIB_DIR=/usr/local/lib/jcheng-system
UNIT=jcheng-system-readonly.service
START=1
[[ "${1:-}" == "--no-start" ]] && START=0

[[ "${EUID}" -ne 0 ]] && exec sudo --preserve-env=PATH bash "$0" "$@"

echo "== token env"
install -d -m 0750 "${ENV_DIR}"
if [[ -f "${ENV_FILE}" ]]; then
    echo "keeping existing ${ENV_FILE}"
else
    umask 077
    token="$(openssl rand -hex 24)"
    # JCHENG_WS must be the workspace root that owns install/setup.bash.
    # Prefer a build of the current checkout; fall back to the M4 artifact.
    ws=/home/ubuntu/jcheng-head/ros2_ws
    root=/home/ubuntu/jcheng-head
    if [[ ! -f "${ws}/install/setup.bash" ]]; then
        ws=/home/ubuntu/jcheng-m4
        root=/home/ubuntu/jcheng-m4/jcheng-system
    fi
    cat > "${ENV_FILE}" <<EOF
# Generated by install-readonly-gateway.sh. Never commit this file.
JCHENG_GATEWAY_TOKEN=${token}
# Workspace built inside the ArmPiUltra container (see README for the build).
JCHENG_WS=${ws}
JCHENG_ROOT=${root}
JCHENG_READONLY_PORT=8767
JCHENG_BUS_SERVICE=/ros_robot_controller/bus_servo/get_state
EOF
    chmod 0600 "${ENV_FILE}"
    echo "wrote ${ENV_FILE} (0600); the token is the only copy outside git"
    echo "workspace: ${ws} (root: ${root})"
fi

echo "== run script and unit"
install -d -m 0755 "${LIB_DIR}"
install -m 0755 "${HERE}/jcheng-system-readonly-run.sh" "${LIB_DIR}/jcheng-system-readonly-run.sh"
install -m 0644 "${HERE}/systemd/${UNIT}" "/etc/systemd/system/${UNIT}"
systemctl daemon-reload

if [[ "${START}" == "1" ]]; then
    echo "== enable and start"
    systemctl enable --now "${UNIT}"
    echo "== wait for /v1/health"
    for _ in $(seq 1 30); do
        if curl -fsS -m 2 -o /dev/null http://127.0.0.1:8767/v1/health; then
            echo "jcheng-system-readonly: /v1/health OK"
            exit 0
        fi
        sleep 1
    done
    echo "ERROR: /v1/health did not answer within 30 s" >&2
    systemctl status "${UNIT}" --no-pager -l | tail -20 >&2
    exit 1
fi
echo "installed (not started)."
