#!/usr/bin/env bash
# Install the hardware-backed R10 vendor gateway on the robot host.
#
# Run on the robot as a user with sudo. The installer writes a root-only
# environment file, installs the run script and systemd unit, and reloads
# systemd. It does not build the workspace, does not touch the vendor
# container and does not enable the unit at boot.
#
#   ./install-gateway-vendor.sh           # install only (default)
#   ./install-gateway-vendor.sh --start   # install + start (operator-authorized)
#
# Starting this unit opens the motion-capable HTTP path. The node starts
# DISARMED and needs a lease before any execution, but the operator is still
# responsible for the per-session authorization. It is not an e-stop.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_DIR=/etc/jcheng-system
ENV_FILE="${ENV_DIR}/vendor.env"
LIB_DIR=/usr/local/lib/jcheng-system
UNIT=jcheng-gateway-vendor.service
START=0

for arg in "$@"; do
    case "$arg" in
        --start) START=1 ;;
        --no-start) START=0 ;;
        -h|--help)
            sed -n '2,14p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
            exit 0
            ;;
        *) echo "unknown argument: $arg" >&2; exit 2 ;;
    esac
done

if [[ "${EUID}" -ne 0 ]]; then
    exec sudo --preserve-env=PATH,JCHENG_GATEWAY_TOKEN,JCHENG_WS,JCHENG_ROOT,JCHENG_VENDOR_WS,JCHENG_INTERFACES_WS,JCHENG_VENDOR_PORT,JCHENG_EVIDENCE \
        bash "$0" "$@"
fi

WS="${JCHENG_WS:-/home/ubuntu/jcheng-r10}"
ROOT="${JCHENG_ROOT:-${WS}}"
VENDOR_WS="${JCHENG_VENDOR_WS:-/home/ubuntu/ros2_ws/install}"
INTERFACES_WS="${JCHENG_INTERFACES_WS:-/home/ubuntu/jcheng-m5/install}"
PORT="${JCHENG_VENDOR_PORT:-8766}"
EVIDENCE="${JCHENG_EVIDENCE:-/home/ubuntu/jcheng-gateway-vendor.jsonl}"

echo "== preflight"
if systemctl is-active --quiet armpi-gateway-pose; then
    echo "ERROR: the legacy pose gateway (armpi-gateway-pose, 8766) is active." >&2
    echo "       Mask or stop it first: the R10 gateway owns 8766." >&2
    exit 1
fi
if systemctl is-active --quiet "${UNIT}"; then
    echo "ERROR: ${UNIT} is already active; stop it before reinstalling." >&2
    exit 1
fi
if ss -ltn 2>/dev/null | grep -q ":${PORT} "; then
    echo "ERROR: port ${PORT} is already in use." >&2
    exit 1
fi
if ! /usr/bin/docker exec -u ubuntu ArmPiUltra test -f "${WS}/install/setup.bash"; then
    echo "ERROR: ${WS}/install/setup.bash is missing inside ArmPiUltra." >&2
    echo "       Copy this checkout to ${WS} and build it inside the container:" >&2
    echo "         source /opt/ros/humble/setup.bash" >&2
    echo "         colcon build --base-paths ros2_ws/src --packages-up-to jcheng_vendor jcheng_bringup" >&2
    exit 1
fi

echo "== token env"
install -d -m 0750 "${ENV_DIR}"
TOKEN="${JCHENG_GATEWAY_TOKEN:-}"
if [[ -z "${TOKEN}" && -r "${ENV_FILE}" ]]; then
    TOKEN="$(sed -n 's/^JCHENG_GATEWAY_TOKEN=//p' "${ENV_FILE}" | head -1)"
fi
if [[ -z "${TOKEN}" ]]; then
    TOKEN="$(openssl rand -hex 24)"
fi
umask 077
cat > "${ENV_FILE}" <<EOF
# Generated by install-gateway-vendor.sh. Never commit this file.
JCHENG_GATEWAY_TOKEN=${TOKEN}
JCHENG_WS=${WS}
JCHENG_ROOT=${ROOT}
JCHENG_VENDOR_WS=${VENDOR_WS}
JCHENG_INTERFACES_WS=${INTERFACES_WS}
JCHENG_VENDOR_PORT=${PORT}
JCHENG_EVIDENCE=${EVIDENCE}
EOF
chmod 0600 "${ENV_FILE}"
echo "wrote ${ENV_FILE} (0600); the token is the only copy outside git"

echo "== run script and unit"
install -d -m 0755 "${LIB_DIR}"
install -m 0755 "${HERE}/jcheng-gateway-vendor-run.sh" "${LIB_DIR}/jcheng-gateway-vendor-run.sh"
install -m 0644 "${HERE}/systemd/${UNIT}" "/etc/systemd/system/${UNIT}"
systemctl daemon-reload
# The unit is manual-start only: never enable a motion gateway at boot.
systemctl disable "${UNIT}" >/dev/null 2>&1 || true

if [[ "${START}" == "1" ]]; then
    echo "== start (motion-capable, DISARMED until a lease)"
    systemctl start "${UNIT}"
    for _ in $(seq 1 30); do
        if curl -fsS -m 2 -o /dev/null "http://127.0.0.1:${PORT}/v1/health"; then
            echo "jcheng-gateway-vendor: /v1/health OK on 127.0.0.1:${PORT}"
            exit 0
        fi
        sleep 1
    done
    echo "ERROR: /v1/health did not answer within 30 s" >&2
    systemctl status "${UNIT}" --no-pager -l | tail -20 >&2
    exit 1
fi

cat <<EOF
installed (not started, not enabled at boot).

Start per session:   systemctl start ${UNIT}
Stop:                systemctl stop ${UNIT}
Studio wiring:       ARMPI_GATEWAY_V1_URL=http://127.0.0.1:${PORT}
                     ARMPI_GATEWAY_V1_TOKEN=<token from ${ENV_FILE}>
                     ARMPI_SYSTEM_STOP=1
The gateway binds 127.0.0.1; use an SSH tunnel from the console host.
EOF
